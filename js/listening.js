function highlight(){
  if(!pendingSelection)return;
  const text=pendingSelection.text.trim();
  const r=pendingSelection.range.cloneRange();
  const root=$('questionArea');
  if(!root || r.collapsed || !root.contains(r.startContainer) || !root.contains(r.endContainer))return;
  const ancestor=(r.commonAncestorContainer.nodeType===1?r.commonAncestorContainer:r.commonAncestorContainer.parentElement);
  const existing=ancestor?.closest?.('mark.hl-brown, mark.hl-pink');
  try{
    if(existing && existing.textContent.trim()===text){
      if(existing.classList.contains('hl-brown')){
        existing.className='hl-pink';
        existing.setAttribute('style','background-color:#FF007F!important;color:#FFF!important;display:inline!important;padding:2px 4px!important;border-radius:2px!important;');
        setSavedHighlight(text,'hl-pink');
      }else{
        const frag=document.createDocumentFragment();
        while(existing.firstChild)frag.appendChild(existing.firstChild);
        existing.replaceWith(frag);
        setSavedHighlight(text,'none');
      }
    }else{
      // Range-aware wrapping works even when the selected text crosses
      // multiple text nodes/elements.
      wrapSelectedRange(r,'hl-brown');
      setSavedHighlight(text,'hl-brown');
    }
  }catch(err){
    console.error('Highlight failed',err);
  }
  $('selectionMenu').classList.remove('show');
  pendingSelection=null;
  try{getSelection().removeAllRanges()}catch{}
}
