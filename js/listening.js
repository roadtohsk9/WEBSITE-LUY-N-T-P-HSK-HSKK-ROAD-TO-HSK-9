function collectListeningAnswersFromDOM(){
  const seen=new Set();
  document.querySelectorAll('[data-q]').forEach(el=>{
    const id=String(el.dataset.q||'').trim(); if(!id)return;
    if(el.type==='checkbox'){
      if(seen.has(id))return; seen.add(id);
      currentAnswers[id]=[...document.querySelectorAll(`[data-q="${CSS.escape(id)}"]`)]
        .filter(x=>x.type==='checkbox'&&x.checked).map(x=>x.value).join('|');
    }else if(el.type==='radio'){
      if(el.checked)currentAnswers[id]=el.value;
    }else{
      currentAnswers[id]=el.value;
    }
  });
}

function save(){
  collectListeningAnswersFromDOM();
  /* Keep the legacy loop for compatibility with existing radio/checkbox state. */
  document.querySelectorAll('[data-q]').forEach(el=>{
    if(el.type==='checkbox'){
      const id=el.dataset.q;
      const vals=[...document.querySelectorAll(`[data-q="${CSS.escape(id)}"]:checked`)].map(x=>x.value);
      currentAnswers[id]=vals.join('|');
    } else if(el.type==='radio'){
      if(el.checked) currentAnswers[el.dataset.q]=el.value;
    } else currentAnswers[el.dataset.q]=el.value;
  });
  localStorage.setItem('listeningAnswers',JSON.stringify(currentAnswers));
}
